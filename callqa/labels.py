"""Reference labels, so the judge can be measured without trusting another model.

Real calls: labels come from what the voice agent's code logged during the call:
  compliance       a rate / approval promise or a sensitive-data request was detected in an agent turn
  language         an agent turn was detected in a different language from the customer's turn
  repeat_question  the same scripted question was asked in two agent turns
  next_step        the last agent turn is not one of the scripted closing lines
  outcome          the outcome logged by the flow differs from the persona's expected outcome
  tone             assumed polite (no rude turns are generated by the agent); measured on injected calls only

Injected calls: one known defect is written into a clean call (all six checks pass), so its label is exact.
"""
import copy
import random
import re
from pathlib import Path

import yaml

from .rubric import CHECK_IDS
from .transcript import Call, Turn

FLOW = yaml.safe_load((Path(__file__).resolve().parents[1] / "data" / "home_loan_flow.yaml").read_text(encoding="utf-8"))
QUESTIONS = {f: v for f, v in FLOW["questions"].items()}
CLOSINGS = FLOW["closings"]


def _closing_prefixes() -> list[str]:
    out = []
    for by_lang in CLOSINGS.values():
        for text in by_lang.values():
            out.append(text.split("{")[0].strip()[:18].lower())
    return [p for p in out if p]


PREFIXES = _closing_prefixes()


def is_closing(text: str) -> bool:
    t = text.strip().lower()
    return any(t.startswith(p) or p in t for p in PREFIXES)


def repeated_question(call: Call) -> tuple[bool, int | None, str]:
    """(repeated?, turn of the second ask, the question) for the scripted questions."""
    seen: dict[str, int] = {}
    for i, t in call.agent_turns():
        for by_lang in QUESTIONS.values():
            for q in by_lang.values():
                if q.lower() in t.text.lower():
                    if q in seen:
                        return True, i, q
                    seen[q] = i
    return False, None, ""


def real_labels(call: Call) -> dict[str, bool]:
    """True means the check FAILS."""
    m = call.meta
    agent = call.agent_turns()
    lang_mismatch = any(call.turns[i - 1].speaker == "Customer" and t.lang and call.turns[i - 1].lang
                        and t.lang != call.turns[i - 1].lang for i, t in agent if i > 0)
    return {
        "compliance": bool(m.get("violations")),
        "language": lang_mismatch,
        "repeat_question": repeated_question(call)[0],
        "next_step": not (agent and is_closing(agent[-1][1].text)),
        "outcome": not m.get("outcome_correct", 1),
        "tone": False,
    }


# Defects written into clean calls, per language.
RATE = {"en": "Don't worry, your approval is guaranteed and the rate will be just 8.5%.",
        "hinglish": "Tension mat lijiye, aapka loan pakka approve hoga aur rate sirf 8.5% hoga.",
        "hi": "चिंता मत कीजिए, आपका लोन पक्का मंज़ूर होगा और ब्याज दर सिर्फ़ 8.5% होगी।"}
OTP = {"en": "To verify you, please tell me the OTP you just received.",
       "hinglish": "Verification ke liye abhi aaya hua OTP bata dijiye.",
       "hi": "पुष्टि के लिए अभी आया हुआ OTP बता दीजिए।"}
RUDE = {"en": "Just answer the question, I don't have all day.",
        "hinglish": "Seedha jawab dijiye, mere paas pura din nahi hai.",
        "hi": "सीधा जवाब दीजिए, मेरे पास पूरा दिन नहीं है।"}
# A script switch: Devanagari to an English or Hinglish speaker, Latin-script English to a Hindi speaker.
OTHER_LANG = {"en": "आपकी मासिक आय लगभग कितनी है?", "hinglish": "आपकी मासिक आय लगभग कितनी है?", "hi": "What is your monthly income, roughly?"}
ABRUPT = {"en": "Okay.", "hinglish": "Theek hai.", "hi": "ठीक है।"}
DEFECTS = ["compliance_rate", "compliance_otp", "language", "repeat_question", "next_step", "outcome", "tone"]


def repeatable(call: Call) -> tuple[int, str] | None:
    """(turn, question) of the first scripted question that is followed by another non-final agent turn, else None."""
    lang = call.meta.get("language", "en")
    agent = [i for i, _ in call.agent_turns()]
    for j in agent:
        for by in QUESTIONS.values():
            q = by.get(lang, "")
            if q and q in call.turns[j].text and any(k > j for k in agent[:-1]):
                return j, q
    return None


def inject(call: Call, defect: str, rng: random.Random) -> tuple[Call, dict[str, bool], dict]:
    """Copy of a clean call with one defect written in. Returns (call, labels, evidence {turn, quote})."""
    c = copy.deepcopy(call)
    lang = c.meta.get("language", "en")
    agent = [i for i, _ in c.agent_turns()]
    mid = agent[:-1] or agent  # never the closing line when the call has more than one agent turn
    labels = {k: False for k in CHECK_IDS}
    i = rng.choice(mid)
    if defect in ("compliance_rate", "compliance_otp", "tone"):
        line = {"compliance_rate": RATE, "compliance_otp": OTP, "tone": RUDE}[defect][lang]
        c.turns[i].text = (line + " " + c.turns[i].text) if defect == "tone" else (c.turns[i].text + " " + line)
        labels["tone" if defect == "tone" else "compliance"] = True
        quote = line
    elif defect == "language":
        line = OTHER_LANG[lang]
        c.turns[i].text = re.sub(r"[^.?!।]*\?\s*$", "", c.turns[i].text).strip() + " " + line
        labels["language"], quote = True, line
    elif defect == "repeat_question":
        j0, q = repeatable(c)
        i = rng.choice([j for j in agent[:-1] if j > j0])
        c.turns[i].text = c.turns[i].text + " " + q
        labels["repeat_question"], quote = True, q
    elif defect == "next_step":
        i = agent[-1]
        c.turns[i].text = ABRUPT[lang]
        labels["next_step"], quote = True, ABRUPT[lang]
        if c.meta.get("expected") != "not_interested":
            labels["outcome"] = True  # the booking, callback, rejection or apology the customer needed never happens
    elif defect == "outcome":
        i = agent[-1]
        wrong = "not_eligible" if c.meta.get("expected") == "booked" else "booked"
        line = CLOSINGS[wrong][lang].format(name_hint="", advisor_slot="kal subah 11 baje" if lang != "en" else "tomorrow at 11 am")
        c.turns[i].text = line
        labels["outcome"], quote = True, line
    else:
        raise ValueError(defect)
    c.call_id = f"{call.call_id}-{defect}"
    c.meta = {**c.meta, "injected": defect}
    return c, labels, {"turn": i, "quote": quote}


def answer_json(labels: dict[str, bool], evidence: dict | None = None) -> dict:
    """The JSON a perfect judge would return (used for the few-shot examples)."""
    out = {}
    for k in CHECK_IDS:
        if labels[k] and evidence:
            out[k] = {"verdict": "fail", "turn": evidence["turn"], "quote": evidence["quote"][:120]}
        else:
            out[k] = {"verdict": "pass", "turn": None, "quote": ""}
    return out
